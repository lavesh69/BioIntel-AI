from __future__ import annotations

import io
import json
from typing import Any, Sequence


def conversation_markdown(title: str, messages: Sequence[dict[str, Any]]) -> str:
    lines = [f"# {title}", "", "Generated by BioIntel Shiro AI.", ""]
    for item in messages:
        role = "Shiro AI" if item.get("role") == "assistant" else "User"
        lines.extend((f"## {role}", "", str(item.get("content", "")), ""))
        citations = item.get("citations") or []
        if citations:
            lines.append("### Evidence")
            for citation in citations:
                lines.append(f"- [{citation.get('citation_id', '')}] {citation.get('source_title', '')} · {citation.get('location', '')}")
            lines.append("")
    return "\n".join(lines)


def conversation_json(messages: Sequence[dict[str, Any]]) -> bytes:
    return json.dumps(list(messages), indent=2, ensure_ascii=False).encode("utf-8")


def conversation_docx(title: str, messages: Sequence[dict[str, Any]]) -> bytes:
    from docx import Document

    document = Document()
    document.add_heading(title, 0)
    document.add_paragraph("Generated by BioIntel Shiro AI")
    for item in messages:
        document.add_heading("Shiro AI" if item.get("role") == "assistant" else "User", level=1)
        document.add_paragraph(str(item.get("content", "")))
        citations = item.get("citations") or []
        if citations:
            document.add_heading("Evidence", level=2)
            for citation in citations:
                document.add_paragraph(f"[{citation.get('citation_id', '')}] {citation.get('source_title', '')} · {citation.get('location', '')}", style="List Bullet")
    output = io.BytesIO()
    document.save(output)
    return output.getvalue()


def conversation_pdf(title: str, messages: Sequence[dict[str, Any]]) -> bytes:
    from reportlab.lib.enums import TA_LEFT
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.lib.units import mm
    from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer

    output = io.BytesIO()
    doc = SimpleDocTemplate(output, pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm, topMargin=18 * mm, bottomMargin=18 * mm)
    styles = getSampleStyleSheet()
    body = ParagraphStyle("ShiroBody", parent=styles["BodyText"], leading=15, alignment=TA_LEFT, spaceAfter=8)
    story = [Paragraph(title, styles["Title"]), Paragraph("Generated by BioIntel Shiro AI", styles["Italic"]), Spacer(1, 10)]
    for item in messages:
        story.append(Paragraph("Shiro AI" if item.get("role") == "assistant" else "User", styles["Heading2"]))
        safe = str(item.get("content", "")).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("\n", "<br/>")
        story.append(Paragraph(safe, body))
        for citation in item.get("citations") or []:
            cite = f"[{citation.get('citation_id', '')}] {citation.get('source_title', '')} · {citation.get('location', '')}"
            story.append(Paragraph(cite.replace("&", "&amp;"), styles["Bullet"]))
        story.append(Spacer(1, 8))
    doc.build(story)
    return output.getvalue()
