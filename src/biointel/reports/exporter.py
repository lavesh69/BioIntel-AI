"""
BioIntel AI — Multi-Format Scientific Report Exporter
Exports research evidence, RAG answers, and multi-omics analysis results to Markdown, JSON, and HTML/PDF formats.
"""
from __future__ import annotations

import json
from dataclasses import asdict, dataclass
from typing import Any, Sequence


@dataclass
class ExportableReport:
    title: str
    project_id: str
    generated_at_utc: str
    summary_text: str
    citations: tuple[dict[str, Any], ...]
    confidence_score: str
    language: str


class ScientificReportExporter:
    """Exports scientific reports and evidence to standard open formats."""

    @staticmethod
    def to_markdown(report: ExportableReport) -> str:
        md_lines = [
            f"# 📄 {report.title}",
            f"**Project ID:** `{report.project_id}` | **Generated:** {report.generated_at_utc} | **Confidence:** {report.confidence_score}\n",
            "---",
            "## 📝 Executive Summary\n",
            report.summary_text,
            "\n---",
            "## 📚 Verified Evidence Citations\n",
        ]

        if report.citations:
            for cit in report.citations:
                cit_id = cit.get("citation_id", "CIT-01")
                fn = cit.get("filename", "Evidence File")
                loc = cit.get("location", "N/A")
                excerpt = cit.get("excerpt", "")
                md_lines.append(f"### [{cit_id}] {fn} (Location: {loc})")
                md_lines.append(f"> {excerpt}\n")
        else:
            md_lines.append("*No external evidence attached.*")

        md_lines.append("\n---\n*Report generated by BioIntel AI Scientific Platform v15.6.0*")
        return "\n".join(md_lines)

    @staticmethod
    def to_json(report: ExportableReport) -> str:
        return json.dumps(asdict(report), indent=2, ensure_ascii=False)
