def prioritize_pages_for_role(pages: list[PageDefinition], role: str) -> list[PageDefinition]:
    priorities = ROLE_PAGE_PRIORITIES.get(role, ())
    rank = {key: index for index, key in enumerate(priorities)}
    return sorted(
        pages,
        key=lambda page: (
            0 if page.key in rank else 1,
            rank.get(page.key, 10_000),
            0 if page.featured else 1,
            page.category,
            page.title,
        ),
    )


def _search_match(page: PageDefinition, needle: str) -> PageSearchMatch:
    from biointel.ui.search_quality import score_search_candidate

    detail = score_search_candidate(
        needle,
        title=page.title,
        description=page.description,
        category=page.category,
        keywords=page.keywords,
        key=page.key,
    )
    return PageSearchMatch(
        page=page,
        score=detail.score,
        corrected_query=detail.corrected_query,
        matched_terms=detail.matched_terms,
        reasons=detail.reasons,
    )


def _search_score(page: PageDefinition, needle: str) -> float:
    return _search_match(page, needle).score


def search_page_matches(
    query: str = "",
    category: str | None = None,
    favourites: set[str] | None = None,
) -> list[PageSearchMatch]:
    needle = " ".join(query.strip().lower().split())
    favourite_keys = favourites or set()
    normalized_category = CATEGORY_ALIASES.get(category, category) if category else category
    matches: list[PageSearchMatch] = []
    for page in PAGE_CATALOG:
        if (
            normalized_category
            and normalized_category != "All"
            and page.category != normalized_category
        ):
            continue
        match = _search_match(page, needle)
        if needle and match.score < 2.35:
            continue
        matches.append(match)

    # During an active query, scientific relevance always outranks favourites.
    # With an empty query, pinned pages remain the preferred discovery surface.
    if needle:
        matches.sort(
            key=lambda item: (
                -item.score,
                item.page.key not in favourite_keys,
                not item.page.featured,
                item.page.category,
                item.page.title,
            )
        )
    else:
        matches.sort(
            key=lambda item: (
                item.page.key not in favourite_keys,
                not item.page.featured,
                item.page.category,
                item.page.title,
            )
        )
    return matches


def adjacent_pages(page_key: str) -> tuple[PageDefinition | None, PageDefinition | None]:
    """Return the previous and next modules inside the active scientific domain.

    Domain-scoped movement prevents a generic next button from jumping users into
    an unrelated workflow while still providing predictable back/forward movement.
    """

    active = PAGE_BY_KEY.get(page_key)
    if active is None:
        return None, None
    peers = [page for page in PAGE_CATALOG if page.category == active.category]
    try:
        index = next(i for i, page in enumerate(peers) if page.key == page_key)
    except StopIteration:
        return None, None
    previous_page = peers[index - 1] if index > 0 else None
    next_page = peers[index + 1] if index + 1 < len(peers) else None
    return previous_page, next_page


def search_pages(
    query: str = "",
    category: str | None = None,
    favourites: set[str] | None = None,
) -> list[PageDefinition]:
    normalized_category = CATEGORY_ALIASES.get(category, category) if category else category
    ordered = [match.page for match in search_page_matches(query, category, favourites)]
    # Preserve historical caller-facing category labels while keeping the
    # canonical catalogue free of duplicate Modeling/Modelling sections.
    if category in CATEGORY_ALIASES and CATEGORY_ALIASES[category] == normalized_category:
        return [replace(page, category=category) for page in ordered]
    return ordered





