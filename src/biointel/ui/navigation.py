def catalogue_integrity(project_root: str | Path | None = None) -> dict[str, object]:
    root = Path(project_root).resolve() if project_root else Path(__file__).resolve().parents[3]
    actual = {path.relative_to(root).as_posix() for path in (root / "pages").glob("*.py")}
    registered = {page.path for page in PAGE_CATALOG if page.path.startswith("pages/")}
    duplicate_keys = sorted({page.key for page in PAGE_CATALOG if sum(1 for item in PAGE_CATALOG if item.key == page.key) > 1})
    duplicate_paths = sorted({page.path for page in PAGE_CATALOG if sum(1 for item in PAGE_CATALOG if item.path == page.path) > 1})
    return {
        "page_files": len(actual),
        "catalogue_pages": len(registered),
        "missing_from_catalogue": sorted(actual - registered),
        "missing_on_disk": sorted(registered - actual),
        "auto_discovered": [page.path for page in _AUTO_DISCOVERED_PAGES],
        "duplicate_keys": duplicate_keys,
        "duplicate_paths": duplicate_paths,
        "healthy": not (actual - registered or registered - actual or duplicate_keys or duplicate_paths),
    }




