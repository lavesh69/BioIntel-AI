def _fallback_title(path: Path) -> str:
    stem = re.sub(r"^\d+_", "", path.stem)
    return re.sub(r"_+", " ", stem).strip().title() or path.stem


def _fallback_key(path: Path) -> str:
    base = re.sub(r"^\d+_", "", path.stem).lower()
    key = re.sub(r"[^a-z0-9]+", "_", base).strip("_")
    return f"auto_{key}"


def discover_unregistered_pages(project_root: str | Path | None = None) -> tuple[PageDefinition, ...]:
    """Discover Streamlit pages missing from the explicit catalogue.

    Explicit entries remain authoritative.  This guarded fallback prevents newly
    added pages from silently disappearing from global search before metadata is
    curated.  Auto-discovered pages are clearly classified as ``Unclassified``
    and should later receive a normal PageDefinition.
    """

    root = Path(project_root).resolve() if project_root else Path(__file__).resolve().parents[3]
    pages_root = root / "pages"
    if not pages_root.is_dir():
        return ()
    registered = {page.path for page in PAGE_CATALOG}
    discovered: list[PageDefinition] = []
    for file_path in sorted(pages_root.glob("*.py"), key=lambda item: item.name.lower()):
        relative = file_path.relative_to(root).as_posix()
        if relative in registered or file_path.name.startswith("_"):
            continue
        title = _fallback_title(file_path)
        discovered.append(
            PageDefinition(
                key=_fallback_key(file_path),
                path=relative,
                title=title,
                icon="â–¦",
                category="Unclassified",
                description="Automatically discovered page awaiting curated catalogue metadata.",
                keywords=(title.lower(), "auto discovered", "new module"),
                featured=False,
            )
        )
    return tuple(discovered)


