from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class ThemeSpec:
    """Application-wide visual theme tokens.

    Themes use only CSS colours and system font stacks so the offline desktop
    build and hosted web/mobile shells do not depend on third-party font CDNs.
    """

    name: str
    primary: str
    secondary: str
    accent: str
    glow: str
    bg_start: str = "#050814"
    bg_mid: str = "#091020"
    bg_end: str = "#060A14"
    bg_soft: str = "#0D1425"
    surface: str = "rgba(15, 23, 42, 0.74)"
    surface_strong: str = "rgba(17, 25, 45, 0.94)"
    sidebar_start: str = "rgba(9, 14, 30, 0.97)"
    sidebar_end: str = "rgba(5, 9, 20, 0.98)"
    hero_start: str = "rgba(15, 23, 42, 0.90)"
    hero_end: str = "rgba(15, 23, 42, 0.62)"
    text: str = "#F8FAFC"
    muted: str = "#94A3B8"
    description: str = "Professional scientific workspace"
    is_new: bool = False


@dataclass(frozen=True)
class FontSpec:
    """A local-first CSS font stack with deterministic fallbacks."""

    name: str
    css_stack: str
    plotly_family: str
    category: str
    description: str
    is_new: bool = False


